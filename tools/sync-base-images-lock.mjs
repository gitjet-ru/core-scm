#!/usr/bin/env node
import {writeFile} from 'node:fs/promises';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';

const execFileAsync = promisify(execFile);

const registryBase = process.env.REGISTRY_BASE || 'REGISTRY_BASE';
const images = [
  {imageKey: 'ALPINE_3_23_IMAGE', refKey: 'ALPINE_3_23_REF', image: `${registryBase}/alpine-base:3.23`},
  {imageKey: 'ALPINE_3_19_IMAGE', refKey: 'ALPINE_3_19_REF', image: `${registryBase}/alpine-base:3.19`},
  {imageKey: 'GOLANG_1_26_ALPINE_3_23_IMAGE', refKey: 'GOLANG_1_26_ALPINE_3_23_REF', image: `${registryBase}/golang-base:1.26-alpine3.23`},
];

function parseDigest(output, imageRef) {
  const match = output.match(/Digest:\s*(sha256:[a-f0-9]+)/i);
  if (!match) {
    throw new Error(`Unable to detect digest for ${imageRef}`);
  }
  return match[1];
}

async function inspectDigest(imageRef) {
  const {stdout} = await execFileAsync('docker', ['buildx', 'imagetools', 'inspect', imageRef], {
    maxBuffer: 10 * 1024 * 1024,
  });
  return parseDigest(stdout, imageRef);
}

async function main() {
  if (registryBase === 'REGISTRY_BASE') {
    console.error('REGISTRY_BASE is not set. Example: REGISTRY_BASE=registry.company.local/gitjet/base');
    process.exit(1);
  }

  const rows = [];
  rows.push('# Internal base image lock (immutable digests).');
  rows.push('# Generated by: node tools/sync-base-images-lock.mjs');

  for (const item of images) {
    const digest = await inspectDigest(item.image);
    const repo = item.image.split(':')[0];
    rows.push(`${item.imageKey}=${item.image}`);
    rows.push(`${item.refKey}=${repo}@${digest}`);
  }

  rows.push('');
  await writeFile('compliance/base-images.lock', `${rows.join('\n')}\n`, 'utf8');
  console.log('Updated compliance/base-images.lock');
}

await main();
